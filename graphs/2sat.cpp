struct TWO_SAT {
    int n;
    vector<vi> graph, graph_rev;
    vector<bool> used, ans;
    vi ord, comp;

    TWO_SAT(int n)
        : n(n)
        , graph(2 * n)
        , graph_rev(2 * n)
        , used(2 * n, false)
        , ans(n)
        , comp(2 * n, -1) {}

    void add_impl(int a, int b) {
        graph[a].pb(b);
        graph_rev[b].pb(a);
        graph[b ^ 1].pb(a ^ 1);
        graph_rev[a ^ 1].pb(b ^ 1);
    }

    void add_or(int a, int b) { add_impl(a ^ 1, b); }

    void set(int i, bool val) {
        int u = 2 * i + (val ? 0 : 1);
        add_impl(u ^ 1, u);
    }

    void dfs1(int v) {
        used[v] = true;
        for (int u: graph[v]) {
            if (!used[u]) {
                dfs1(u);
            }
        }
        ord.pb(v);
    }

    void dfs2(int v, int color) {
        comp[v] = color;
        for (int u: graph_rev[v]) {
            if (comp[u] == -1) {
                dfs2(u, color);
            }
        }
    }

    bool get_ans() {
        fill(all(used), false);
        ord.clear();
        fill(all(comp), -1);
        for (int i = 0; i < 2 * n; ++i) {
            if (!used[i]) dfs1(i);
        }
        int color = 0;
        for (int i = sz(ord) - 1; i >= 0; --i) {
            int v = ord[i];
            if (comp[v] == -1) {
                dfs2(v, color++);
            }
        }
        for (int i = 0; i < n; ++i) {
            if (comp[2 * i] == comp[2 * i + 1]) {
                return false;
            }
            ans[i] = comp[2 * i] > comp[2 * i + 1];
        }
        return true;
    }
};

