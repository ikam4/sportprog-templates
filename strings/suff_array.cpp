vi suff_array(string s) {
    s += '\0';
    int n = sz(s);
    const int alphabet = 256;
    vi p(n), cnt(max(alphabet, n), 0);
    vi c(n), pn(n), cn(n);
    for (int i = 0; i < n; ++i) c[i] = (unsigned char) s[i];
    for (int x: c) cnt[x]++;
    for (int i = 1; i < alphabet; ++i) cnt[i] += cnt[i - 1];
    for (int i = 0; i < n; ++i) p[--cnt[c[i]]] = i;
    cn[p[0]] = 0;
    int classes = 1;
    for (int i = 1; i < n; ++i) {
        if (c[p[i]] != c[p[i - 1]]) classes++;
        cn[p[i]] = classes - 1;
    }
    swap(c, cn);
    for (int h = 0; (1 << h) < n; ++h) {
        int shift = 1 << h;
        for (int i = 0; i < n; ++i) {
            pn[i] = p[i] - shift;
            if (pn[i] < 0) pn[i] += n;
        }
        fill(cnt.begin(), cnt.begin() + classes, 0);
        for (int i = 0; i < n; ++i) cnt[c[pn[i]]]++;
        for (int i = 1; i < classes; ++i) cnt[i] += cnt[i - 1];
        for (int i = n - 1; i >= 0; --i) p[--cnt[c[pn[i]]]] = pn[i];
        cn[p[0]] = 0;
        classes = 1;
        for (int i = 1; i < n; ++i) {
            int r1 = p[i] + shift, r2 = p[i - 1] + shift;
            if (r1 >= n) r1 -= n;
            if (r2 >= n) r2 -= n;
            if (c[p[i]] != c[p[i - 1]] || c[r1] != c[r2]) classes++;
            cn[p[i]] = classes - 1;
        }
        swap(c, cn);
        if (classes == n) break;
    }
    return vi(p.begin() + 1, p.end());
}

vi lcp(string_view s, const vi& sa) {
    int n = sz(s);
    if (n <= 1) return {};
    vi rank(n);
    for (int i = 0; i < n; ++i) {
        rank[sa[i]] = i;
    }
    vi lcp(n - 1, 0);
    int k = 0;
    for (int i = 0; i < n; ++i) {
        if (rank[i] == n - 1) {
            k = 0;
            continue;
        }
        int j = sa[rank[i] + 1];
        while (i + k < n && j + k < n && s[i + k] == s[j + k]) {
            ++k;
        }
        lcp[rank[i]] = k;
        if (k > 0) {
            --k;
        }
    }
    return lcp;
}

